#!/usr/bin/env bash
set -Eeuo pipefail

cd "$(dirname "$0")/.."

repo=${1:-${GITHUB_REPOSITORY:-}}
build_id=${2:-${BUILD_ID:-}}
branch=${EXTRAS_BRANCH:-packages}
# Only feeds that carry optional third-party packages need an extras URL.
# app_airoha/onu_config/pon_drivers/argon packages are part of the image; the
# official distfeeds cover luci/packages/routing/telephony.  Keeping this list
# short also guarantees that every URL below has a non-empty index.
feeds=${EXTRAS_FEEDS:-"helloworld pushbot"}

if [[ -z "$repo" ]]; then
	remote=$(git remote get-url origin 2>/dev/null || true)
	repo=$(sed -nE 's#.*github\.com[:/]([^/]+/[^/]+)(\.git)?$#\1#p' <<<"$remote" | head -n 1)
fi

if [[ -z "$repo" || -z "$build_id" ]]; then
	echo "usage: $0 <owner/repo> <build-id>" >&2
	echo "   or: GITHUB_REPOSITORY=... BUILD_ID=... $0" >&2
	exit 1
fi
if [[ ! "$build_id" =~ ^[0-9A-Za-z._-]+$ ]]; then
	echo "invalid build id: $build_id" >&2
	exit 1
fi

base=${EXTRAS_BASE_URL:-https://raw.githubusercontent.com/$repo/$branch/$build_id}

mkdir -p files/etc/apk/repositories.d
{
	echo "# XG2010G extras for build $build_id."
	echo "# Generated by scripts/set-extras-repo.sh; do not edit on the device."
	for feed in $feeds; do
		echo "$base/$feed/packages.adb"
	done
	echo "$base/kmods/packages.adb"
	# Optional packages from this repository's own package/ tree (lucky).
	echo "$base/local/packages.adb"
} > files/etc/apk/repositories.d/xg2010g.list

for feed in $feeds; do
	echo "extras feed: $base/$feed/packages.adb"
done
echo "extras feed: $base/kmods/packages.adb"
echo "extras feed: $base/local/packages.adb"
